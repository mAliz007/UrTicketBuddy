import { z } from "zod";

export enum ErrorCode {
  UNAUTHORIZED = "UNAUTHORIZED",
  FORBIDDEN = "FORBIDDEN",
  NOT_FOUND = "NOT_FOUND",
  VALIDATION_ERROR = "VALIDATION_ERROR",
  CONFLICT = "CONFLICT",
  EMAIL_ALREADY_EXISTS = "EMAIL_ALREADY_EXISTS",
  INVALID_CREDENTIALS = "INVALID_CREDENTIALS",
  INVALID_REFRESH_TOKEN = "INVALID_REFRESH_TOKEN",
  TOO_MANY_REQUESTS = "TOO_MANY_REQUESTS",
  SEAT_ALREADY_HELD = "SEAT_ALREADY_HELD",
  SEAT_ALREADY_SOLD = "SEAT_ALREADY_SOLD",
  SEAT_NOT_HELD_BY_YOU = "SEAT_NOT_HELD_BY_YOU",
  HOLD_EXPIRED = "HOLD_EXPIRED",
  TOO_MANY_SEATS = "TOO_MANY_SEATS",
  IDEMPOTENCY_CONFLICT = "IDEMPOTENCY_CONFLICT",
  PAYMENT_FAILED = "PAYMENT_FAILED",
  TICKET_NOT_FOUND = "TICKET_NOT_FOUND",
  TICKET_ALREADY_USED = "TICKET_ALREADY_USED",
  TICKET_EXPIRED = "TICKET_EXPIRED",
  TICKET_INVALID = "TICKET_INVALID",
  TICKET_FORGED = "TICKET_FORGED",
  WRONG_EVENT = "WRONG_EVENT",
  RESALE_PRICE_CAP_EXCEEDED = "RESALE_PRICE_CAP_EXCEEDED",
  INTERNAL_SERVER_ERROR = "INTERNAL_SERVER_ERROR",
  INVALID_FILE_TYPE = "INVALID_FILE_TYPE",
  FILE_TOO_LARGE = "FILE_TOO_LARGE",
  STORAGE_ERROR = "STORAGE_ERROR",
  STRUCTURE_LOCKED = "STRUCTURE_LOCKED",
  UNPROCESSABLE_ENTITY = "UNPROCESSABLE_ENTITY",
}

export const ErrorEnvelopeSchema = z.object({
  error: z.object({
    code: z.nativeEnum(ErrorCode),
    message: z.string(),
    details: z.unknown().optional(),
    requestId: z.string().optional(),
  }),
});

export type ErrorEnvelope = z.infer<typeof ErrorEnvelopeSchema>;
